#!/usr/bin/env node
/**
 * src/observability/bootGuard.es5.js → src/observability/bootGuard.min.ts.
 *
 * The guard is inlined into every app's index.html, so it is minified here,
 * once, with the oxc minifier Vite already brought (rolldown/utils) — not in
 * the app's build. oxc has no ES5 target and prints strings as `templates`, so
 * those are turned back into "strings" from the AST, and the result is checked
 * for anything newer than ES5: the guard runs on whatever browser restored the
 * page, before any polyfill. `npm run build` runs this; the output is committed
 * so `npm run check` (tsc) works on a fresh clone.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { minifySync, parseSync } from "rolldown/utils"

const SRC = new URL("../src/observability/bootGuard.es5.js", import.meta.url)
const OUT = new URL("../src/observability/bootGuard.min.ts", import.meta.url)
export const PLACEHOLDER = "KIT_BOOT_GUARD_CONFIG"

function walk(node, visit) {
  if (!node || typeof node !== "object") return
  if (Array.isArray(node)) return node.forEach((n) => walk(n, visit))
  if (typeof node.type === "string") visit(node)
  for (const k of Object.keys(node)) if (k !== "start" && k !== "end") walk(node[k], visit)
}

/** Syntax newer than ES5 in `code`, as a list of "Type@offset". Empty = ES5. */
export function es5Violations(code) {
  const { program, errors } = parseSync("guard.js", code)
  if (errors.length) return errors.map((e) => `ParseError ${e.message}`)
  const out = []
  const banned = new Set([
    "ArrowFunctionExpression", "TemplateLiteral", "TaggedTemplateExpression", "ClassDeclaration",
    "ClassExpression", "SpreadElement", "RestElement", "ObjectPattern", "ArrayPattern",
    "AssignmentPattern", "ForOfStatement", "AwaitExpression", "YieldExpression", "ChainExpression",
    "ImportExpression", "MetaProperty",
  ])
  walk(program, (n) => {
    if (banned.has(n.type)) out.push(`${n.type}@${n.start}`)
    if (n.type === "VariableDeclaration" && n.kind !== "var") out.push(`${n.kind}@${n.start}`)
    if (n.type === "Property" && (n.shorthand || n.method || n.computed)) out.push(`Property@${n.start}`)
    if (n.type === "CatchClause" && !n.param) out.push(`catch{}@${n.start}`)
    if (n.type === "LogicalExpression" && n.operator === "??") out.push(`??@${n.start}`)
    if (n.type === "AssignmentExpression" && /^(\?\?|\|\||&&|\*\*)=$/.test(n.operator)) out.push(`${n.operator}@${n.start}`)
    if (n.type === "BinaryExpression" && n.operator === "**") out.push(`**@${n.start}`)
    if (n.type === "FunctionExpression" || n.type === "FunctionDeclaration") {
      if (n.async || n.generator) out.push(`async/generator@${n.start}`)
    }
    if (n.type === "Literal" && (typeof n.value === "bigint" || n.regex?.flags?.match(/[suyd]/))) out.push(`Literal@${n.start}`)
  })
  return out
}

/** The readable source → one ES5 line, ASCII only, ending in `(KIT_BOOT_GUARD_CONFIG);`. */
export function minifyGuard(source) {
  // es2015 is the oldest target oxc takes; it keeps catch (e) bindings.
  let code = minifySync("guard.js", source, { compress: { target: "es2015" }, mangle: true }).code.trim()
  // Back down to ES5 from the AST, edits applied from the end so offsets
  // hold: `templates` without ${} → "strings", { a } → { a: a }.
  const edits = []
  walk(parseSync("guard.js", code).program, (n) => {
    if (n.type === "TemplateLiteral" && n.expressions.length === 0) {
      edits.push([n.start, n.end, JSON.stringify(n.quasis[0].value.cooked)])
    }
    if (n.type === "Property" && n.shorthand && n.key.type === "Identifier") {
      edits.push([n.start, n.end, `${n.key.name}:${n.key.name}`])
    }
  })
  edits.sort((a, b) => b[0] - a[0])
  for (const [start, end, text] of edits) code = code.slice(0, start) + text + code.slice(end)
  // ASCII only: the page's charset is not ours to assume.
  code = code.replace(/[^\x00-\x7f]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`)
  const bad = es5Violations(code)
  if (bad.length) throw new Error(`boot guard is not ES5 after minify: ${bad.join(", ")}`)
  if (!code.includes(PLACEHOLDER)) throw new Error(`boot guard lost ${PLACEHOLDER}`)
  return code
}

export function render(code) {
  return `// GENERATED by scripts/build-boot-guard.mjs from bootGuard.es5.js — edit that, then \`npm run build\`.
export const GUARD_SOURCE = ${JSON.stringify(code)}
export const GUARD_PLACEHOLDER = ${JSON.stringify(PLACEHOLDER)}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = minifyGuard(readFileSync(SRC, "utf8"))
  const next = render(code)
  let prev = ""
  try { prev = readFileSync(OUT, "utf8") } catch { /* first run */ }
  if (prev !== next) writeFileSync(OUT, next)
  console.log(`boot guard: ${code.length} bytes minified${prev === next ? "" : " (bootGuard.min.ts updated)"}`)
}
